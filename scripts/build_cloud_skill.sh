#!/usr/bin/env bash
# Build the cloud skill copy and template.sha from workflow/dev-workflow.md.
#
# Usage: scripts/build_cloud_skill.sh [out-dir]
#
# Writes <out-dir>/cloud/dev-workflow/SKILL.md and <out-dir>/template.sha.
# out-dir defaults to the repo root. Edit only the workflow file, run this
# script, and commit both outputs; checks/20-cloud-copy.sh fails if they drift.
#
# template.sha holds the first 12 hex chars of the sha256 of the workflow
# file. SKILL.md carries the same value on its "Template sha256:" line, then
# the workflow body with the lines before its first "# " heading dropped.

set -eu

repo=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$repo}
workflow="$repo/workflow/dev-workflow.md"

if [ ! -f "$workflow" ]; then
  echo "missing $workflow" >&2
  exit 1
fi
mkdir -p "$out/cloud/dev-workflow"

python3 - "$workflow" "$out" <<'PY'
import hashlib
import os
import sys

workflow, out = sys.argv[1], sys.argv[2]

NAME = "dev-workflow"
DESCRIPTION = (
    "Coding workflow: which skill runs when (Matt Pocock skills plus "
    "changeable-software), parallel ticket waves, and the rules for cloud "
    "sessions. Use at the start of any coding task."
)

with open(workflow, "rb") as f:
    raw = f.read()
sha = hashlib.sha256(raw).hexdigest()[:12]

lines = raw.decode("utf-8").splitlines(True)
start = next((i for i, line in enumerate(lines) if line.startswith("# ")), None)
if start is None:
    sys.exit("no '# ' heading in " + workflow)
body = "".join(lines[start:])

header = (
    "---\n"
    "name: " + NAME + "\n"
    'description: "' + DESCRIPTION + '"\n'
    "---\n"
    "\n"
    "> Generated from workflow/dev-workflow.md by scripts/build_cloud_skill.sh. "
    "Do not edit this file; edit the workflow file and run the script.\n"
    ">\n"
    "> Template sha256: " + sha + "\n"
    "\n"
)


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


write(os.path.join(out, "cloud", "dev-workflow", "SKILL.md"), header + body)
write(os.path.join(out, "template.sha"), sha + "\n")
PY
